// Exact authored turn + exact actual speaker, never a text mention or name guess.
// An explicit off-screen/voice-only override always suppresses a portrait.
export function openingPortrait(turn) {
  if (!turn || turn.offscreen === true || turn.voiceOnly === true ||
      turn.stage?.portraitAllowed === false || turn.stage?.offscreen === true ||
      ['offscreen', 'voice-only', 'voice'].includes(turn.stage?.presence) ||
      ['offscreen', 'voice-only', 'voice'].includes(turn.delivery)) return null;
  const binding = bindings[turn.id];
  if (!binding || binding.speaker !== turn.speaker || !binding.portrait) return null;
  return OPENING_PORTRAITS[binding.portrait] ?? null;
}
export function applyOpeningPortrait(image, turn, fallback) {
  const art = openingPortrait(turn);
  image.hidden = !art;
  if (!art) return null;
  image.setAttribute('data-character-id', art.id);
  image.width = art.width; image.height = art.height;
  image.alt = `${art.name} · 沿用已验收角色头像`;
  image.src = new URL('../../' + art.file, import.meta.url).href;
  image.onerror = () => {
    image.hidden = true;
    if (fallback) { fallback.textContent = `${art.name}的头像暂未载入，可继续阅读`; fallback.hidden = false; }
  };
  return art;
}
